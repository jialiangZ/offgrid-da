#!/usr/bin/env python3
"""Control experiment: separate input-storage precision from execution precision.

A = fp32 inputs, fp32 exec   (what test_fp16_inputs.py accidentally did)
B = fp32 inputs, bf16 exec   (production pipeline: run_aifs_background.py has the
                              bf16 autocast monkeypatch from the OOM era)
C = fp16 inputs, bf16 exec   (the ACTUAL fp16-storage question)

Baseline = data/bg_aifs_2021 (generated by production = B-config).
"""
import datetime as dt
from pathlib import Path

import numpy as np
import torch
import anemoi.inference.runner as _R
from anemoi.inference.runners.simple import SimpleRunner
from earthkit.regrid.db import find as find_matrix

HERE = Path(__file__).resolve().parent
CKPT = str(HERE / "v1.1" / "aifs-single-mse-1.1.ckpt")
IN = HERE / "data" / "aifs_inputs" / "2021"
BASE = HERE / "data" / "bg_aifs_2021"

STAMP = "2021010106"  # output = state_20210101T12
PRESS = [50, 100, 150, 200, 250, 300, 400, 500, 600, 700, 850, 925, 1000]
NAMES = ["2t", "10u", "10v", "2d", "msl", "sp", "skt", "tcw", "stl1", "stl2", "swvl1", "swvl2"] + \
    [f"{b}_{lv}" for b in ("u", "v", "t", "w", "z", "q") for lv in PRESS]
OUT_NAMES = ["10u", "10v", "2t", "msl"] + [f"{b}_{lv}" for b in ("z", "u", "v", "t", "q", "w") for lv in PRESS]

_orig_run = _R.Runner.run


def _run_bf16(self, *a, **k):
    with torch.autocast("cuda", dtype=torch.bfloat16):
        return _orig_run(self, *a, **k)


def fp16_roundtrip(arr):
    out = np.empty_like(arr)
    for i in range(arr.shape[0]):
        v = arr[i]
        scale = 60000.0 / float(np.abs(v).max())
        out[i] = (v * scale).astype(np.float16).astype(np.float32) / scale
    return out


def main():
    runner = SimpleRunner(CKPT, device="cuda")
    z_in, _ = find_matrix({"grid": (0.25, 0.25)}, {"grid": "N320"}, "linear")
    z_out, out_shape = find_matrix({"grid": "N320"}, {"grid": (1.5, 1.5)}, "linear")
    consts = np.load(HERE / "data" / "aifs_inputs" / "constants_0p25.npy")
    cn = (z_in @ consts.reshape(4, -1).T).T
    const_fields = {n: np.stack([v, v]) for n, v in zip(("lsm", "z", "slor", "sdor"), cn)}

    t = dt.datetime(2021, 1, 1, 6)
    prev = np.load(IN / "2021010100.npy")
    cur = np.load(IN / "2021010106.npy")

    def forecast(fp16_inputs, bf16_exec):
        flat = np.empty((180, 721 * 1440), dtype=np.float32)
        prep = fp16_roundtrip if fp16_inputs else (lambda a: a.astype(np.float32))
        flat[0::2] = prep(prev).reshape(90, -1)
        flat[1::2] = prep(cur).reshape(90, -1)
        n320 = (z_in @ flat.T).T
        fields = {n: n320[2 * i:2 * i + 2].copy() for i, n in enumerate(NAMES)}
        fields.update(const_fields)
        fn = _run_bf16 if bf16_exec else _orig_run
        result = list(fn(runner, input_state=dict(date=t, fields=fields), lead_time="6h"))[-1]
        arr = np.stack([np.asarray(result["fields"][n], np.float32) for n in OUT_NAMES])
        assert np.isfinite(arr).all()
        return (z_out @ arr.T).T.reshape(82, *out_shape)

    A = forecast(False, False)   # fp32 in, fp32 exec
    B = forecast(False, True)    # fp32 in, bf16 exec  (= production)
    C = forecast(True, True)     # fp16 in, bf16 exec  (= the real question)

    base = np.load(BASE / "state_20210101T12.npz")
    w = np.cos(np.deg2rad(np.linspace(90, -90, 121)))[:, None]

    def rmse(x, y):
        return float(np.sqrt((((x - y).astype(np.float64)) ** 2 * w).mean()))

    rows = [("2t", A[2], B[2], C[2], base["surface"][2, 0]),
            ("msl", A[3], B[3], C[3], base["surface"][3, 0]),
            ("10u", A[0], B[0], C[0], base["surface"][0, 0]),
            ("t_850", A[4 + 39 + 10], B[4 + 39 + 10], C[4 + 39 + 10], base["level"][3, 10]),
            ("z_500", A[4 + 7], B[4 + 7], C[4 + 7], base["level"][0, 7]),
            ("u_850", A[4 + 13 + 10], B[4 + 13 + 10], C[4 + 13 + 10], base["level"][1, 10])]
    print(f"{'ch':>5} {'A-fp32exec':>11} {'B-fp32in':>10} {'C-fp16in':>10} {'A vs B':>10} {'C vs B':>10}")
    for n, a, b, c, ref in rows:
        print(f"{n:>5} {rmse(a, ref):>11.4f} {rmse(b, ref):>10.4f} {rmse(c, ref):>10.4f} "
              f"{rmse(a, b):>10.4f} {rmse(c, b):>10.4f}")
    print("\nA vs B = execution-precision effect (fp32 vs bf16 forward)")
    print("C vs B = TRUE fp16-storage effect (what the user asked)")


if __name__ == "__main__":
    main()
